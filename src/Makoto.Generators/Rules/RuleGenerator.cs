using System.Linq;
using System.Text;
using Makoto.Generators.Model;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Makoto.Generators.Rules;

/// <summary>Emits one extension class per [ValidationRule] class.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class RuleGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(RuleDiscovery.Create(context), static (output, result) =>
        {
            foreach (var diagnostic in result.Diagnostics)
            {
                output.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (result.Rule is { } rule)
            {
                output.AddSource(HintName(rule), SourceText.From(Emit(rule), Encoding.UTF8));
            }
        });
    }

    private static string HintName(RuleInfo rule)
    {
        // The namespace is escaped for keywords (@event), which AddSource rejects in a hint name.
        var prefix = rule.Namespace is null ? "" : $"{rule.Namespace.Replace("@", "")}.";
        var arity = rule.TypeParameters.Length == 0 ? "" : $"_{rule.TypeParameters.Length}";
        return $"{prefix}{rule.ClassName}{arity}.Rule.g.cs";
    }

    internal static string Emit(RuleInfo rule)
    {
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable enable");
        code.AppendLine("#pragma warning disable");
        code.AppendLine();

        if (rule.Namespace is not null)
        {
            code.AppendLine($"namespace {rule.Namespace};");
            code.AppendLine();
        }

        if (rule.EmitSealed)
        {
            var typeParameters = rule.TypeParameters.Length == 0 ? "" : $"<{string.Join(", ", rule.TypeParameters)}>";
            code.AppendLine($"sealed partial class {Identifier(rule.ClassName)}{typeParameters};");
            code.AppendLine();
        }

        // Partial because Foo and Foo<T> share this class. The suffix keeps a keyword class name (event) a valid identifier.
        code.AppendLine($"{rule.Accessibility} static partial class {rule.ClassName}Extensions");
        code.AppendLine("{");

        var isGeneric = rule.TypeParameters.Length != 0;
        var typeArguments = isGeneric ? $"<{string.Join(", ", rule.TypeParameters)}>" : "";
        var constraints = string.Concat(rule.Constraints.Select(c => $" {c}"));
        var instance = isGeneric ? $"Holder{typeArguments}.Instance" : "s_rule";

        if (isGeneric)
        {
            code.AppendLine($"    private static class Holder{typeArguments}{constraints}");
            code.AppendLine("    {");
            code.AppendLine($"        internal static readonly {rule.QualifiedName} Instance = new();");
            code.AppendLine("    }");
        }
        else
        {
            code.AppendLine($"    private static readonly {rule.QualifiedName} s_rule = new();");
        }

        var receiverName = "value";
        while (rule.Arguments.Any(a => a.Name == receiverName))
        {
            receiverName = $"_{receiverName}";
        }

        var parameters = string.Concat(rule.Arguments.Select(a => $", {a.Type} {Identifier(a.Name)}"));
        var arguments = string.Concat(rule.Arguments.Select(a => $", {Identifier(a.Name)}"));
        var ruleTypeOf = isGeneric
            ? $"{rule.QualifiedName.Substring(0, rule.QualifiedName.IndexOf('<'))}<{new string(',', rule.TypeParameters.Length - 1)}>"
            : rule.QualifiedName;
        var attributes =
            $"    [global::Makoto.GeneratedRule(typeof({ruleTypeOf}), {Literal(rule.Code)}, {Literal(rule.Message)})]\n" +
            "    [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]";

        void Method(string receiver, string body)
        {
            code.AppendLine();
            code.AppendLine(attributes);
            code.AppendLine($"    public static bool {rule.MethodName}{typeArguments}(this {receiver} {receiverName}{parameters}){constraints} => {body};");
        }

        var call = $"{instance}.Evaluate({receiverName}{arguments})";
        switch (rule.ValueKind)
        {
            case RuleValueKind.NonNullableReference:
                Method($"{rule.ValueType}?", $"{receiverName} is not null && {call}");
                break;
            case RuleValueKind.PassThrough:
                Method(rule.ValueType, call);
                break;
            case RuleValueKind.ValueType:
                Method(rule.ValueType, call);
                Method($"{rule.ValueType}?", $"{receiverName}.HasValue && {instance}.Evaluate({receiverName}.GetValueOrDefault(){arguments})");
                break;
        }

        code.AppendLine("}");
        return code.ToString();
    }

    private static string Identifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : $"@{name}";

    private static string Literal(string value) =>
        SymbolDisplay.FormatLiteral(value, quote: true);
}
