namespace Makoto.Generators.Tests.Validators;

/// <summary>Holds the generated text to the shape in docs/design.md.</summary>
public class GeneratedShapeTests
{
    private const string Design = """
        using System.Collections.Generic;
        using Makoto;
        namespace Demo;

        public sealed class Address { public string? City { get; set; } }

        public sealed class Signup
        {
            public string? Email { get; set; }
            public Address? Address { get; set; }
            public IEnumerable<string> Tags { get; set; } = [];
        }

        [ValidationRule(Message = "'{PropertyName}' is not an email address.")]
        public sealed class IsEmailValidationRule : ValidationRule<string>
        {
            public override bool Evaluate(string value) => value.Contains('@');
        }

        [ValidationRule(Message = "'{PropertyName}' must not be empty.")]
        public sealed class FilledRule : ValidationRule<string>
        {
            public override bool Evaluate(string value) => value.Length != 0;
        }

        [Validator]
        public sealed partial class AddressValidator : Validator<Address>
        {
            protected override void Configure()
            {
                Property(x => x.City).Require(x => x.Filled());
            }
        }

        [Validator]
        public sealed partial class SignupValidator : Validator<Signup>
        {
            protected override void Configure()
            {
                Property(x => x.Email)
                    .Require(x => x.IsEmail()).When(x => x is not null)
                    .Require(x => x.Length < 200).WithMessage("Too long.").WithCode("TooLong");

                Property(x => x.Address).ValidateWith<AddressValidator>();

                Each(x => x.Tags).Require(x => x.Filled());
            }
        }
        """;

    [Fact]
    public void Matches_the_design_document()
    {
        var result = GeneratorHarness.Run(Design);
        ValidatorHarness.AssertClean(result);

        var code = result.Generated("Demo.SignupValidator");
        string[] expected =
        [
            "// <auto-generated/>",
            "#nullable enable",
            "#pragma warning disable",
            "using System.Collections.Generic;",
            "namespace Demo;",
            "sealed partial class SignupValidator",
            """private static readonly global::Makoto.ValidationFailure s_failure0 = new("Email", "IsEmail", "'Email' is not an email address.");""",
            """private static readonly global::Makoto.ValidationFailure s_failure1 = new("Email", "TooLong", "Too long.");""",
            """private static readonly global::Makoto.ValidationFailure s_failure2 = new("", "Filled", "'Tags' must not be empty.");""",
            "public override global::Makoto.ValidationResult Validate(global::Demo.Signup instance)",
            "public override bool IsValid(global::Demo.Signup instance) => Check(instance);",
            "public static bool Check(global::Demo.Signup instance)",
            "global::System.ArgumentNullException.ThrowIfNull(instance);",
            "var value0 = Select0(instance);",
            "if (When0(value0) && !Require0(value0)) return false;",
            "if (!Require1(value0)) return false;",
            "if (value1 is not null && !global::Demo.AddressValidator.Check(value1)) return false;",
            "public static void ValidateInto(global::Demo.Signup instance, ref global::Makoto.FailureCollector failures)",
            "if (When0(value0) && !Require0(value0)) failures.Add(s_failure0);",
            "if (!Require1(value0)) failures.Add(s_failure1);",
            "global::Demo.AddressValidator.ValidateInto(value1, ref failures);",
            """failures.PrefixFrom(start1, "Address");""",
            "foreach (var item2 in items2)",
            "if (!Require2(item2)) failures.Add(s_failure2);",
            """failures.PrefixFrom(start2, "Tags", index2);""",
            "private static string? Select0(global::Demo.Signup x) => x.Email;",
            "private static bool Require0(string? x) => x.IsEmail();",
            "private static bool When0(string? x) => x is not null;",
            "private static global::Demo.Address? Select1(global::Demo.Signup x) => x.Address;",
        ];

        foreach (var line in expected)
        {
            Assert.Contains(line, code);
        }
    }

    /// <summary>
    /// foreach over an interface can box its enumerator. An indexable one walks a span when it holds a List or an
    /// array, and is indexed otherwise.
    /// </summary>
    [Fact]
    public void Each_over_an_indexable_interface_is_a_for_loop()
    {
        var result = GeneratorHarness.Run("""
            using System.Collections.Generic;
            using Makoto;

            public sealed class M
            {
                public IReadOnlyList<string>? Labels { get; set; }
                public IList<int> Counts { get; set; } = [];
                public IEnumerable<string> Tags { get; set; } = [];
            }

            [Validator]
            public sealed partial class V : Validator<M>
            {
                protected override void Configure()
                {
                    Each(x => x.Labels).Require(x => x.Length != 0);
                    Each(x => x.Counts).Require(x => x > 0);
                    Each(x => x.Tags).Require(x => x.Length != 0);
                }
            }
            """);

        ValidatorHarness.AssertClean(result);
        var code = result.Generated("V");
        string[] expected =
        [
            "if (items0 is not null)",
            "if (items0 is global::System.Collections.Generic.List<string> list0) span0 = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(list0);",
            "else if (items0 is string[] array0) span0 = array0;",
            "for (var index0 = 0; index0 < span0.Length; index0++)",
            "var item0 = span0[index0];",
            "if (items1 is global::System.Collections.Generic.List<int> list1) span1 = global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(list1);",
            "else if (items1 is int[] array1) span1 = array1;",
            "for (var index0 = 0; index0 < items0.Count; index0++)",
            "var item0 = items0[index0];",
            """failures.PrefixFrom(start0, "Labels", index0);""",
            "for (var index1 = 0; index1 < items1.Count; index1++)",
            "var item1 = items1[index1];",
            "foreach (var item2 in items2)",
        ];

        foreach (var line in expected)
        {
            Assert.Contains(line, code);
        }

        Assert.DoesNotContain("foreach (var item0", code);
        Assert.DoesNotContain("foreach (var item1", code);
        Assert.DoesNotContain("index0++;", code);
    }
}
